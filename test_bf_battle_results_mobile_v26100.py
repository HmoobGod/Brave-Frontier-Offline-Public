"""v261: read-only mobile battle result action UI regression.

The real v30 results component injects its styles after the navigation CSS.
This isolated fixture reproduces that cascade without changing gameplay or save.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
A = ROOT / "app/src/main/assets"
CSS = (A / "bf_home_nav.css").read_text("utf8")
NAV = (A / "bf_home_nav.js").read_text("utf8")
RESULTS = (A / "bf3000_battle_results.js").read_text("utf8")
PRE = (ROOT / ".github/workflows/android-back-ui-source-preflight.yml").read_text("utf8")
WF = (ROOT / ".github/workflows/build-debug-apk.yml").read_text("utf8")
MAN = (ROOT / "app/src/main/AndroidManifest.xml").read_text("utf8")

MARKER = "/* v261 battle results mobile presentation"
assert CSS.count(MARKER) == 1
PATCH = CSS.split(MARKER, 1)[1]
for required in (
    "#resultpanel #bf3000-result", "#bf3000-heading",
    "#bf3000-reward", "#bf3000-meta", "#bf3000-note",
    "#resultpanel #bf3000-actions", "#bf3000-actions button",
    "min-height:50px", "overflow-wrap:anywhere", "touch-action:manipulation",
    ":focus-visible", "button:disabled", "button[hidden]", "display:none!important",
    "@media(max-width:359px)", "grid-template-columns:minmax(0,1fr)",
    "grid-template-columns:repeat(2,minmax(0,1fr))",
):
    assert required in PATCH, required
for forbidden in (
    "localStorage.", "saveProgress(", "P.gems", "P.questClears",
    "S.party", "S.enemies", "window.", "document.", "fetch(",
    "XMLHttpRequest(", "setInterval(", "onclick=",
):
    assert forbidden not in PATCH, forbidden
assert "'#bf3000-actions button{min-height:44px;" in RESULTS
for required in ("bf3000-replay", "bf3000-next", "bf3000-scene",
                 "SIMULATED CAMPAIGN REWARDS", "DEFEAT · No rewards"):
    assert required in RESULTS, required
assert "test_bf_battle_results_mobile_v26100.py --source-only" in PRE
assert WF.count("python3 test_bf_battle_results_mobile_v26100.py") == 1
assert "android.permission.INTERNET" not in MAN
assert len(CSS.encode("utf8")) < 128 * 1024
assert len(NAV.encode("utf8")) < 128 * 1024
print("PASS v261 source: UI-only result action sizing and hidden/disabled safeguards")
if "--source-only" in sys.argv[1:]:
    raise SystemExit(0)

import shutil
from playwright.sync_api import sync_playwright

chrome = (shutil.which("chromium") or shutil.which("google-chrome") or
          shutil.which("google-chrome-stable"))
assert chrome, "Chromium is required for battle result responsive checks"
end = "\n})();"
bootstrap = end.join(NAV.split(end)[:2]) + end
fixture = """<!doctype html><html><head><meta charset="utf-8"></head><body>
<main class="wrap">
<section class="progresspanel">Save controls</section>
<section class="squadsetup">Units</section>
<section class="summonpanel">Demo recruitment</section>
<section class="questpanel"><div id="questlist">Quest</div></section>
<section id="resultpanel" class="resultpanel">
<div id="results"><strong>Results of demo battle</strong></div>
<section id="bf3000-result" aria-label="Offline demo battle result and navigation">
<h3 id="bf3000-heading">BATTLE CLEARED · Very Long Archived Global Mission Name Which Must Wrap</h3>
<p id="bf3000-reward">SIMULATED CAMPAIGN REWARDS: 100 EXP · 1000 Zel · 100 Karma · Demo tokens only</p>
<p id="bf3000-meta">A long original dungeon name · 6/6 active allies survived · Not native Global rewards</p>
<div id="bf3000-actions">
<button type="button" id="bf3000-replay">REPLAY MISSION ↻</button>
<button type="button" id="bf3000-next" disabled>NEXT STORY MISSION ›</button>
<button type="button" id="bf3000-scene" hidden>READ ORIGINAL CLEAR SCENE ›</button>
</div>
<small id="bf3000-note">Offline simulated battle rewards, and original enemy AI, enemy waves, and costs remain DEMO.</small>
</section></section></main></body></html>"""
# Runtime CSS generated by v30 is deliberately injected later, as in Android.
runtime_css = """
#bf3000-result{border-top:1px solid #a88d62;margin:12px 0 0;padding:12px 0 4px}
#bf3000-result h3{margin:0 0 6px}
#bf3000-actions{display:flex;gap:7px;flex-wrap:wrap;margin:9px 0}
#bf3000-actions button{min-height:44px;padding:8px 12px;border:1px solid #d6b682}
#bf3000-actions button:disabled{opacity:.4}
#bf3000-note{font:11px/1.4 system-ui,sans-serif}
"""
with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True, executable_path=chrome,
                                 args=["--no-sandbox", "--disable-dev-shm-usage"])
    for width in (320, 359, 360, 393, 412, 540):
        page = browser.new_page(viewport={"width":width,"height":760})
        errors = []
        page.on("pageerror", lambda err: errors.append(str(err)))
        page.set_content(fixture)
        page.add_style_tag(content=CSS)
        page.add_script_tag(content=bootstrap)
        page.add_style_tag(content=runtime_css)
        page.locator('.bf-navbar button[data-bf-goto="quest"]').click()
        panel = page.locator("#bf3000-result")
        assert panel.is_visible(), width
        assert page.locator("#bf3000-next").is_disabled(), width
        assert page.locator("#bf3000-scene").is_hidden(), width
        columns = page.locator("#bf3000-actions").evaluate(
            "e=>getComputedStyle(e).gridTemplateColumns.split(/\\s+/).length")
        assert columns == (1 if width <= 359 else 2), (width, columns)
        for selector in ("#bf3000-replay", "#bf3000-next"):
            props = page.locator(selector).evaluate("""e=>{
              const c=getComputedStyle(e),r=e.getBoundingClientRect();
              return {minHeight:parseFloat(c.minHeight),height:r.height,
                left:r.left,right:r.right,wrap:c.overflowWrap,touch:c.touchAction}
            }""")
            assert props["height"]>=50 and props["minHeight"]>=50, (width,props)
            assert props["left"]>=-1 and props["right"]<=width+1, (width,props)
            assert props["wrap"]=="anywhere" and props["touch"]=="manipulation", (width,props)
        page.locator("#bf3000-scene").evaluate("e=>e.hidden=false")
        assert page.locator("#bf3000-scene").is_visible(), width
        assert page.locator("#bf3000-scene").evaluate(
            "e=>e.getBoundingClientRect().height")>=50, width
        for textsel in ("#bf3000-heading","#bf3000-reward",
                        "#bf3000-meta","#bf3000-note"):
            props=page.locator(textsel).evaluate("""e=>{
               const c=getComputedStyle(e),r=e.getBoundingClientRect();
               return {wrap:c.overflowWrap,left:r.left,right:r.right}
            }""")
            assert props["wrap"]=="anywhere" and props["left"]>=-1 and props["right"]<=width+1, (width,props)
        page.evaluate("window.__replays=0;document.querySelector('#bf3000-replay').addEventListener('click',()=>window.__replays++)")
        page.locator("#bf3000-replay").click()
        assert page.evaluate("window.__replays")==1, width
        page.keyboard.press("Tab")
        page.locator("#bf3000-replay").focus()
        assert page.locator("#bf3000-replay").evaluate("e=>e.matches(':focus-visible')"), width
        assert page.locator("#bf3000-replay").evaluate(
            "e=>getComputedStyle(e).outlineStyle")!="none", width
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth+1"), width
        panel.evaluate("e=>e.hidden=true")
        assert panel.is_hidden(), width
        panel.evaluate("e=>e.hidden=false")
        page.locator('.bf-navbar button[data-bf-goto="home"]').click()
        assert panel.is_hidden() and page.locator("#bf-home").is_visible(), width
        assert not errors, (width,errors)
        page.close()
    browser.close()
print("PASS v261 Chromium: 6 mobile widths, battle result readability, disabled/hidden/focus, and route safety")
